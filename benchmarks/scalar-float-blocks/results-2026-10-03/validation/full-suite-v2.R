.libPaths(c('<scalar-block-evidence>/candidate-v2/library', .libPaths()))
library(dtatools)
library(testthat)
results <- testthat::test_dir('<scalar-block-evidence>/candidate-v2/source/tests/testthat', package='dtatools', load_package='installed', reporter='silent', stop_on_failure=FALSE)
frame <- as.data.frame(results)
write.csv(frame[c('file','test','passed','failed','error','skipped','warning')], '<scalar-block-evidence>/candidate-v2-full.csv', row.names=FALSE)
print(colSums(frame[c('passed','failed','error','skipped','warning')]))
cat('Test blocks:', nrow(frame), '\n')
stopifnot(!any(frame$failed), !any(frame$error), !any(frame$skipped))
