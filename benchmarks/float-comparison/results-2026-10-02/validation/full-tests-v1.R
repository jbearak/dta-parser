.libPaths(c('<private-work>/candidate-v1/library', .libPaths()))
library(dtatools)
library(testthat)
stopifnot(identical(normalizePath(getNamespaceInfo(asNamespace('dtatools'), 'path')), '<private-work>/candidate-v1/library/dtatools'))
results <- testthat::test_dir('<private-work>/candidate-v1/source/tests/testthat', package='dtatools', load_package='installed', reporter='silent', stop_on_failure=FALSE)
frame <- as.data.frame(results)
write.csv(frame[c('file','test','passed','failed','error','skipped','warning')], '<private-work>/full-tests-v1.csv', row.names=FALSE)
print(colSums(frame[c('passed','failed','error','skipped','warning')]))
stopifnot(!any(frame$failed), !any(frame$error), !any(frame$skipped))
