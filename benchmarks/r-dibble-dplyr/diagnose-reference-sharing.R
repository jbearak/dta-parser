args <- commandArgs(TRUE)
.libPaths(c(args[[1L]], .libPaths()))
suppressPackageStartupMessages(library(dtatools))
rows <- 5000000L
warmup <- data.frame(compact = dta_byte(1:2))
for (i in 1:5) replace_values(warmup, compact, 2, where=1)
data <- data.frame(compact = dta_byte(rep(1,rows)), untouched=runif(rows))
path <- tempfile()
Rprofmem(path, threshold=1000)
for (i in 1:3) replace_values(data, compact, 2, where=rows)
Rprofmem(NULL)
lines <- readLines(path)
n <- suppressWarnings(as.numeric(sub(" .*", "", lines)))
print(lines[!is.na(n) & n >= rows])
stopifnot(max(n,na.rm=TRUE)<rows)
