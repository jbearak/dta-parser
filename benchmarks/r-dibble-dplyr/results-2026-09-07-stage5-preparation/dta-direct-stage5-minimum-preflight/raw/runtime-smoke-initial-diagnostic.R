by <- dplyr::mutate(data.frame(g = c(1L, 1L, 2L), x = 1:3), size = dplyr::n(), .by = g)
stopifnot(identical(by$size, c(2L, 2L, 1L)))
rowwise <- dplyr::mutate(dplyr::rowwise(data.frame(x = 1:3)), size = dplyr::n())
stopifnot(identical(rowwise$size, rep(1L, 3L)))
