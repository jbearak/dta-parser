result <- dplyr::mutate(data.frame(x = 1:3), y = x + 1L, size = dplyr::n())
stopifnot(identical(result$y, 2:4), identical(result$size, rep(3L, 3L)))
grouped <- dplyr::mutate(dplyr::group_by(data.frame(g = c(1L, 1L, 2L), x = 1:3), g), size = dplyr::n())
