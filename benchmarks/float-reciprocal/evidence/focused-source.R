args <- commandArgs(TRUE)
stopifnot(length(args) == 3L)
lib <- normalizePath(args[[1L]], mustWork = TRUE)
.libPaths(c(lib, .libPaths()))
suppressPackageStartupMessages(library(testthat))
stopifnot(identical(normalizePath(find.package('dtatools')), file.path(lib,'dtatools')))
results <- testthat::test_dir(normalizePath(args[[3L]], mustWork=TRUE), package='dtatools', load_package='installed', filter='^(native-arithmetic-parity|arithmetic-payload-lifetime)$', reporter='summary', stop_on_failure=FALSE)
frame <- as.data.frame(results)
write.csv(frame[c('file','test','passed','failed','error','skipped','warning')], args[[2L]], row.names=FALSE)
stopifnot(!any(frame$failed), !any(frame$error), !any(frame$skipped), !any(frame$warning))
