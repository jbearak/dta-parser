library(dtatools)
library(dplyr)
cc <- function(name, ...) .Call(get(name, asNamespace('dtatools')), ...)
n <- 100000L
columns <- setNames(lapply(seq_len(100L), function(j) rep(as.double(j), n)), c('x', paste0('spare', 2:100)))
d <- as_dibble(tibble::as_tibble(columns))
for (i in seq_along(d)) cc('C_dtatools_set_data_column', d, as.integer(i), cc('C_dtatools_owned_plain_snapshot', .subset2(d, i)))
rm(columns)
warm <- mutate(d, y = x + 1)
rm(warm)
invisible(gc())
before <- cc('C_dtatools_probe_dplyr_early_stats', FALSE)
log <- paste0(args[[2]], '-allocations.txt')
utils::Rprofmem(log)
result <- mutate(d, y = x + 1)
utils::Rprofmem(NULL)
after <- cc('C_dtatools_probe_dplyr_early_stats', FALSE)
lines <- readLines(log)
allocations <- as.double(sub(' .*', '', lines[grepl('^[0-9]+ ', lines)]))
observed <- list(bytes = sum(allocations), native_publications = (after - before)[[3L]], source = as.double(d$x)[[1L]], result = as.double(result$y)[[1L]], pass = sum(allocations) < 16 * 1024^2)
dput(observed, paste0(args[[2]], '-result.txt'))
print(observed)
stopifnot(observed$native_publications == 1L, observed$source == 1, observed$result == 2, observed$pass)
