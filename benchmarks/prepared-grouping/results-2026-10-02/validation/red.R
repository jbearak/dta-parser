counts <- .Call(dtatools:::C_dtatools_egen_group_stats, FALSE)
print(counts)
stopifnot(identical(as.double(y), as.double(match(as.double(x), sort(unique(as.double(x)))))))
stopifnot(counts[["scalar_values"]] + counts[["prepared_values"]] <= n)
