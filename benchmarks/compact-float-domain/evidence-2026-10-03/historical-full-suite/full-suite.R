args <- commandArgs(trailingOnly = TRUE)
.libPaths(c(args[[1L]], .libPaths()))
library(dtatools)
library(testthat)
results <- testthat::test_dir(args[[2L]], package='dtatools', load_package='installed', reporter='silent', stop_on_failure=FALSE)
frame <- as.data.frame(results)
write.csv(frame[c('file','test','passed','failed','error','skipped','warning')], args[[3L]], row.names=FALSE)
print(colSums(frame[c('passed','failed','error','skipped','warning')]))
cat('Test blocks:', nrow(frame), '\n')
stopifnot(!any(frame$failed), !any(frame$error), !any(frame$skipped))
