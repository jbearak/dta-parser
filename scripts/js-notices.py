"""Write js/THIRD-PARTY-NOTICES: the licences of the crates compiled into
the npm package's wasm module (feature wasm-dta), from each crate's own
licence file in cargo's registry. Run after the module's crates change:

    python3 scripts/js-notices.py

It reads the crate list from `cargo tree` for the wasm target, so the
crates must have been fetched (any cargo build does that).
"""

import glob
import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Where a crate offers a choice, the licence the notices carry, by file.
PREFER = ["LICENSE-MIT", "LICENSE-MIT.md", "LICENSE", "COPYING", "LICENSE.BSD-3-Clause"]
# Crates whose repository carries the licence file their package lacks.
SAME_AS = {}


def crates(feature):
    out = subprocess.run(
        ["cargo", "tree", "-p", "dta-ffi", "--target", "wasm32-unknown-unknown", "-e", "normal", "--prefix", "none",
         "--no-default-features", "--features", feature],
        cwd=ROOT, check=True, capture_output=True, text=True).stdout
    seen = []
    for line in out.splitlines():
        m = re.match(r"(\S+) v(\S+)( \(.*\))?", line)
        if m and not m.group(3) and (m.group(1), m.group(2)) not in seen:
            seen.append((m.group(1), m.group(2)))
    return sorted(seen)


def source(name, version):
    home = os.environ.get("CARGO_HOME", os.path.expanduser("~/.cargo"))
    found = glob.glob(f"{home}/registry/src/*/{name}-{version}")
    if not found:
        raise SystemExit(f"{name} {version} is not in cargo's registry; run a cargo build first")
    return Path(found[0])


def field(toml, key):
    m = re.search(rf'^{key}\s*=\s*"([^"]*)"', toml, re.M)
    return m.group(1) if m else ""


def notices(package, feature, out):
    found = crates(feature)
    intro = ("and these crates from crates.io, with their\nlicences below" if found
             else "and no crates from crates.io")
    parts = [f"Third-party notices for {package}\n\n"
             "The package's WebAssembly module is built from this repository's Rust code\n"
             f"(GPL-3.0-only; see LICENSE) {intro}. Generated by scripts/js-notices.py.\n"]
    versions = {n: v for n, v in found}
    for name, version in found:
        d = source(name, version)
        toml = (d / "Cargo.toml").read_text()
        lic_dir = d if name not in SAME_AS else source(SAME_AS[name], versions[SAME_AS[name]])
        text = next(((lic_dir / f).read_text() for f in PREFER if (lic_dir / f).is_file()), None)
        if text is None:
            raise SystemExit(f"{name}: no licence file found")
        parts.append(f"\n{'=' * 72}\n{name} {version} ({field(toml, 'license')})\n{field(toml, 'repository')}\n{'=' * 72}\n\n{text.strip()}\n")
    out.write_text("".join(parts))


def main():
    notices("@jbearak/dta-parser", "wasm-dta", ROOT / "js" / "THIRD-PARTY-NOTICES")


if __name__ == "__main__":
    main()
