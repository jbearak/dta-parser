suppressPackageStartupMessages({library(arrow); library(dplyr); library(nanoarrow); library(haven); library(vctrs)})
cat("R", format(getRversion()), " dplyr", format(packageVersion("dplyr")), " vctrs", format(packageVersion("vctrs")), "\n")
tag <- function(v) { t <- na_tag(v); ifelse(is.na(v) & !is.na(t), paste0(".", t), ifelse(is.na(v), ".", format(v))) }
nan_letters <- function(x) { n <- as_nanoarrow_array(x); valid <- !is.na(x) | !is.na(na_tag(x))
  as_arrow_array(nanoarrow_array_modify(n, list(null_count = sum(!valid), buffers = list(as_nanoarrow_array(valid)$buffers[[2]], n$buffers[[2]])))) }
x0 <- c(1, tagged_na("a"), tagged_na("b"), NA, tagged_na("a"))
df <- collect(arrow_table(x = nan_letters(x0), g = letters[1:5]))
cat("after collect():          ", tag(df$x), "\n")
cat("identical bits to input:  ", identical(writeBin(df$x, raw()), writeBin(x0, raw())), "\n")
x <- df$x
p <- function(label, v) cat(sprintf("%-26s %s\n", label, paste(v, collapse = " ")))
p("base unique()", tag(unique(x)))
p("base duplicated()", duplicated(x))
p("base match(x, .a)", match(x, tagged_na("a")))
p("base %in% .b", x %in% tagged_na("b"))
p("base x == .a", x == tagged_na("a"))
p("base table(useNA)", names(table(x, useNA = "always")))
p("base factor() levels", c(levels(factor(x, exclude = NULL))))
p("base split() groups", length(split(seq_along(x), addNA(factor(x)))))
p("base order()", tag(x[order(x)]))
p("base x[c(5,3)]", tag(x[c(5, 3)]))
p("base ifelse(TRUE, x, 0)", tag(ifelse(rep(TRUE, 5), x, 0)))
p("base x * 2", tag(x * 2))
p("vctrs vec_unique()", tag(vec_unique(x)))
p("vctrs vec_group_id()", vec_group_id(x))
p("vctrs vec_in(x, .a)", vec_in(x, tagged_na("a")))
p("dplyr distinct()", tag(distinct(df, x)$x))
gb <- df |> group_by(x) |> summarise(n = n())
p("dplyr group_by() groups", paste(tag(gb$x), gb$n, sep = ":"))
p("dplyr count()", nrow(count(df, x)))
lk <- tibble::tibble(x = c(tagged_na("a"), tagged_na("b")), lab = c("A", "B"))
j <- left_join(df, lk, by = "x", relationship = "many-to-many")
p("dplyr left_join() rows", paste(tag(j$x), j$lab, sep = "=") )
p("dplyr filter(x %in% .a)", tag(filter(df, x %in% tagged_na("a"))$x))
p("dplyr arrange()", tag(arrange(df, x)$x))
p("dplyr mutate(if_else)", tag(mutate(df, y = if_else(g != "z", x, 0))$y))
p("dplyr bind_rows()", tag(bind_rows(df, df)$x))
p("haven is_tagged_na(x,'a')", is_tagged_na(x, "a"))
