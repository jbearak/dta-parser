suppressPackageStartupMessages({library(dplyr); library(dtaparser); library(vctrs); library(bench)})
set.seed(1); n <- 1e7
x <- as.double(sample.int(1000, n, TRUE))
x[sample.int(n, n / 10)] <- tagged_na(sample(letters[1:3], n / 10, TRUE))
x[sample.int(n, n / 20)] <- NA
keys <- getFromNamespace("dta_keys", "dtatools")
k <- keys(x); cat("dta_keys distinct groups:", length(unique(k)), " plain unique():", length(unique(x)), "\n")
lab <- with_labels(x, c(Low = 1, High = 1000))
idx <- sample.int(n, n / 2)
ms <- function(b) sprintf("%7.1f ms", median(as.numeric(b$time[[1]])) * 1e3)
row <- function(label, f_plain, f_lab) cat(sprintf("%-34s plain %s   labelled %s\n", label,
  ms(mark(f_plain(), iterations = 5, check = FALSE)), ms(mark(f_lab(), iterations = 5, check = FALSE))))
row("x + 1", function() x + 1, function() lab + 1)
row("x[idx]", function() x[idx], function() lab[idx])
row("x == 1", function() x == 1, function() lab == 1)
row("sum(x, na.rm = TRUE)", function() sum(x, na.rm = TRUE), function() sum(lab, na.rm = TRUE))
dp <- tibble::tibble(x = x); dl <- tibble::tibble(x = lab)
row("filter(x > 500)", function() filter(dp, x > 500), function() filter(dl, x > 500))
row("group_by(x) |> summarise(n())", function() summarise(group_by(dp, x), n = n()), function() summarise(group_by(dl, x), n = n()))
row("distinct(x)", function() distinct(dp, x), function() distinct(dl, x))
cat(sprintf("%-34s %s\n", "dta_keys(x), the proxy itself", ms(mark(keys(x), iterations = 5, check = FALSE))))
registerS3method("vec_proxy_equal", "dtaparser_labelled", function(x, ...) keys(vec_data(x)), envir = asNamespace("vctrs"))
registerS3method("vec_proxy_compare", "dtaparser_labelled", function(x, ...) keys(vec_data(x)), envir = asNamespace("vctrs"))
registerS3method("vec_proxy_order", "dtaparser_labelled", function(x, ...) keys(vec_data(x)), envir = asNamespace("vctrs"))
g <- summarise(group_by(dl, x), n = n()); cat("with proxies, group_by groups:", nrow(g), "\n")
cat(sprintf("%-34s labelled+proxy %s\n", "group_by(x) |> summarise(n())", ms(mark(summarise(group_by(dl, x), n = n()), iterations = 5, check = FALSE))))
cat(sprintf("%-34s labelled+proxy %s\n", "distinct(x)", ms(mark(distinct(dl, x), iterations = 5, check = FALSE))))
cat(sprintf("%-34s labelled+proxy %s\n", "filter(x > 500)", ms(mark(filter(dl, x > 500), iterations = 5, check = FALSE))))
cat(sprintf("%-34s labelled+proxy %s\n", "arrange(x)", ms(mark(arrange(dl, x), iterations = 3, check = FALSE))))
cat(sprintf("%-34s plain          %s\n", "arrange(x)", ms(mark(arrange(dp, x), iterations = 3, check = FALSE))))
