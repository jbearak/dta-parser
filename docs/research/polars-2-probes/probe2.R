suppressPackageStartupMessages({library(arrow); library(dplyr); library(nanoarrow); library(haven)})
tag <- function(v) { t <- na_tag(v); ifelse(is.na(v) & !is.na(t), paste0(".", t), ifelse(is.nan(v), "NaN", ifelse(is.na(v), ".", format(v)))) }
nan_letters <- function(x) { n <- as_nanoarrow_array(x); valid <- !is.na(x) | !is.na(na_tag(x))
  as_arrow_array(nanoarrow_array_modify(n, list(null_count = sum(!valid), buffers = list(as_nanoarrow_array(valid)$buffers[[2]], n$buffers[[2]])))) }
x <- c(1, tagged_na("a"), tagged_na("b"), NA, tagged_na("a"), 2, tagged_na("b"), NA, NaN)
b <- nan_letters(x); tb <- arrow_table(x = b, g = letters[1:9])
lookup <- arrow_table(x = nan_letters(c(tagged_na("a"), tagged_na("b"), NaN)), lab = c("A", "B", "plainNaN"))
cat("lookup null_count:", lookup$x$null_count, "\n")
j <- tb |> left_join(lookup, by = "x") |> arrange(g) |> collect()
print(data.frame(x = tag(j$x), g = j$g, lab = j$lab))
j2 <- tb |> left_join(lookup, by = "x", na_matches = "never") |> arrange(g) |> collect()
cat("na_matches=never:", paste(tag(j2$x), j2$lab, sep = "=", collapse = " "), "\n")
cat("equal(x, .a):", paste(as.vector(call_function("equal", b, b$Take(rep(1L, 9)))), collapse = " "), "\n")
gb <- tb |> group_by(x) |> summarise(n = n()) |> collect()
cat("group_by incl plain NaN:", paste(tag(gb$x), gb$n, sep = ":", collapse = " "), "\n")
cat("dplyr filter(is.nan(x)):", nrow(tb |> filter(is.nan(x)) |> collect()), "rows\n")
cat("dplyr sum(!is.na(x)):", (tb |> summarise(n = sum(!is.na(x))) |> collect())$n, "\n")
cat("dplyr mean(x, na.rm=TRUE):", format((tb |> summarise(m = mean(x, na.rm = TRUE)) |> collect())$m), "\n")
cat("collect then dplyr group_by in R:", paste(tag((collect(tb) |> group_by(x) |> summarise(n = n()))$x), collapse = " "), "\n")
